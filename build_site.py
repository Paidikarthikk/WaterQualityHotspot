"""Export the report notebook's cleaned dataset to docs/data.js for the website.

Mirrors the pipeline in Water_Quality_EDAV_Report.ipynb:
load all CSVs -> combine -> median-impute measurement columns -> classify
water-body type from the source filename.

Run from anywhere:  python WaterQualityHotspot/build_site.py
"""

import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
RAW_DATA = ROOT / "raw_data"
OUT_FILE = ROOT / "docs" / "data.js"

ID_COLUMNS = ["STATION CODE", "LOCATIONS", "STATE", "SOURCE_FILE"]

# Reference values are the ones printed in the dataset's column headings
PARAMETERS = [
    {"key": "temp", "label": "Temperature", "unit": "°C", "match": "TEMPERATURE", "ref": None},
    {"key": "do", "label": "Dissolved oxygen", "unit": "mg/L", "match": "D.O.", "ref": {"op": "min", "value": 4, "text": "> 4 mg/L"}},
    {"key": "ph", "label": "pH", "unit": "", "match": "pH", "ref": {"op": "range", "value": [6.5, 8.5], "text": "6.5 – 8.5"}},
    {"key": "cond", "label": "Conductivity", "unit": "µmhos/cm", "match": "CONDUCTIVITY", "ref": None},
    {"key": "bod", "label": "BOD", "unit": "mg/L", "match": "B.O.D.", "ref": {"op": "max", "value": 3, "text": "< 3 mg/L"}},
    {"key": "nitrate", "label": "Nitrate + nitrite", "unit": "mg/L", "match": "NITRATE", "ref": None},
    {"key": "fc", "label": "Fecal coliform", "unit": "MPN/100ml", "match": "FECAL COLIFORM", "ref": {"op": "max", "value": 2500, "text": "< 2,500 MPN/100ml"}},
    {"key": "tc", "label": "Total coliform", "unit": "MPN/100ml", "match": "TOTAL COLIFORM", "ref": {"op": "max", "value": 5000, "text": "< 5,000 MPN/100ml"}},
]


def find_column(columns, match, stat):
    return next(c for c in columns if c.startswith(match) and f": {stat}" in c)


def source_name(filename):
    name = re.sub(r"^water_quality_of_|-2013\.csv$", "", filename)
    return name.replace("_", " ").replace("-", " – ").strip().capitalize()


def main():
    csv_files = sorted(RAW_DATA.glob("*.csv"))
    all_data = []
    for file in csv_files:
        df = pd.read_csv(file, encoding="cp1252")
        df["SOURCE_FILE"] = file.name
        all_data.append(df)
    master_df = pd.concat(all_data, ignore_index=True)

    measurement_columns = [c for c in master_df.columns if c not in ID_COLUMNS]

    # Same cleaning as the notebook's final cleaning cell
    raw_numeric = master_df.copy()
    for column in measurement_columns:
        raw_numeric[column] = pd.to_numeric(raw_numeric[column], errors="coerce")
    clean_df = raw_numeric.copy()
    for column in measurement_columns:
        median_value = clean_df[column].median()
        if pd.notna(median_value):
            clean_df[column] = clean_df[column].fillna(median_value)

    clean_df["WATER_BODY_TYPE"] = np.select(
        [
            clean_df["SOURCE_FILE"].str.contains("medium.*minor.*rivers", case=False, regex=True),
            clean_df["SOURCE_FILE"].str.contains("main.rivers", case=False, regex=True),
            clean_df["SOURCE_FILE"].str.contains("tributary.streams", case=False, regex=True),
        ],
        ["Medium/Minor Rivers", "Main Rivers", "Tributary Streams"],
        default="Other/Unclassified",
    )

    mean_cols = {p["key"]: find_column(master_df.columns, p["match"], "Mean") for p in PARAMETERS}
    group_cols = {
        p["key"]: [find_column(master_df.columns, p["match"], s) for s in ("Min", "Max", "Mean")]
        for p in PARAMETERS
    }

    stations = []
    for i, row in clean_df.iterrows():
        stations.append({
            "code": str(row["STATION CODE"]),
            "loc": " ".join(str(row["LOCATIONS"]).split()),
            "state": " ".join(str(row["STATE"]).split()),
            "type": row["WATER_BODY_TYPE"],
            "src": source_name(row["SOURCE_FILE"]),
            "v": {k: round(float(row[c]), 3) for k, c in mean_cols.items()},
            # Parameters whose original value was missing in the raw data
            "imp": [p["key"] for p in PARAMETERS if raw_numeric[group_cols[p["key"]]].loc[i].isnull().any()],
        })

    data = {
        "meta": {
            "files": len(csv_files),
            "rows": int(master_df.shape[0]),
            "columns": int(master_df.shape[1]),
            "missingBefore": int(master_df.isnull().sum().sum()),
            "missingAfter": int(clean_df[measurement_columns + ID_COLUMNS].isnull().sum().sum()),
        },
        "parameters": [{k: v for k, v in p.items() if k != "match"} for p in PARAMETERS],
        "stations": stations,
    }

    OUT_FILE.parent.mkdir(exist_ok=True)
    OUT_FILE.write_text(
        "// Generated by build_site.py from raw_data/*.csv - do not edit by hand\n"
        f"window.WQ_DATA = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    bod = clean_df[mean_cols["bod"]]
    print(f"Wrote {OUT_FILE} ({len(stations)} stations)")
    print("Mean values:", {k: round(clean_df[c].mean(), 3) for k, c in mean_cols.items()})
    print("Stations with BOD mean > 3 mg/L:", int((bod > 3).sum()))
    print("Missing before/after:", data["meta"]["missingBefore"], data["meta"]["missingAfter"])


if __name__ == "__main__":
    main()
